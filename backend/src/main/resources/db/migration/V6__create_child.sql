-- 급식카드로 인증한 아동. 카드 번호 원문은 두지 않고 비밀 키를 섞은 해시(HMAC-SHA256, 소문자 hex 64자)만 둔다.
-- 같은 카드면 같은 해시라 같은 아동으로 찾는다. 이름 같은 개인정보는 두지 않는다.
--
-- qr_credential.child_id·check_in.child_id 에 외래 키는 걸지 않는다 — 아동 인증이 생기기 전에 관리자가 아무 번호로
-- 발급한 QR·체크인 행이 배포본에 남아 있을 수 있어, 걸면 이 마이그레이션이 실패해 기동이 멈춘다.

CREATE TABLE child (
    child_id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_hash  varchar(64)  NOT NULL,
    created_at timestamp(6) NOT NULL,
    updated_at timestamp(6) NOT NULL,
    CONSTRAINT uk_child_card_hash UNIQUE (card_hash)
);

-- 아동 번호를 그 옛 행들의 번호 다음부터 매긴다. 1부터 매기면 관리자가 번호 7 로 발급해 둔 QR·체크인을 처음 인증한
-- 7번 아동이 물려받는다(그 옛 QR 로 이 아동처럼 체크인된다). 빈 DB 에서는 1부터다.
SELECT setval(pg_get_serial_sequence('child', 'child_id'),
              GREATEST((SELECT COALESCE(MAX(child_id), 0) FROM qr_credential),
                       (SELECT COALESCE(MAX(child_id), 0) FROM check_in)) + 1,
              false);
