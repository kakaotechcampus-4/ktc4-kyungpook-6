-- 이 저장소가 Flyway 를 들이기 전까지 쓰던 스키마를 그대로 옮긴 것이다.
-- `ddl-auto: create` 로 빈 DB 에 한 번 만들게 한 뒤 pg_dump 로 받아 왔으므로,
-- Hibernate 가 만들던 것과 글자 그대로 같다.
--
-- 이미 돌고 있는 DB(dev·prod)에는 이 파일이 실행되지 않는다. `baseline-on-migrate` 가
-- 켜져 있어 Flyway 가 "이 DB 는 이미 V1 상태" 로 도장만 찍고 넘어간다. 빈 DB(로컬·CI·테스트)
-- 에서만 실제로 돈다.
--
-- 🚨 이 파일은 고치지 않는다. 스키마를 바꿀 일이 생기면 V2, V3… 를 새로 만든다.

