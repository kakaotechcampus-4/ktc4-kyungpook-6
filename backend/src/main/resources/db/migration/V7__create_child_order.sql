-- 아동이 가게 메뉴 하나를 주문한 기록. 표 이름이 order 가 아닌 이유: SQL·JPQL 예약어다.
--
-- 상태: RECEIVED(접수 대기) → COOKING(조리 중) → DONE(전달 완료), 접수 대기에서만 CANCELED(취소).
-- 메뉴 이름은 주문 당시 값을 복사해 둔다 — 나중에 메뉴 이름이 바뀌거나 메뉴를 지워도 주문은 그대로 읽혀야 한다.
-- 아동 번호는 아동 표를 가리킨다(새 표라 옛 행이 없어 외래 키를 건다).

CREATE TABLE child_order (
    order_id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    child_id           bigint       NOT NULL,
    store_id           bigint       NOT NULL,
    menu_id            bigint       NOT NULL,
    menu_name          varchar(50)  NOT NULL,
    receive_type       varchar(20)  NOT NULL,
    status             varchar(20)  NOT NULL,
    cooking_started_at timestamp(6),
    completed_at       timestamp(6),
    canceled_at        timestamp(6),
    created_at         timestamp(6) NOT NULL,
    updated_at         timestamp(6) NOT NULL,
    CONSTRAINT fk_child_order_child FOREIGN KEY (child_id) REFERENCES child (child_id),
    CONSTRAINT fk_child_order_store FOREIGN KEY (store_id) REFERENCES store (store_id),
    CONSTRAINT fk_child_order_menu FOREIGN KEY (menu_id) REFERENCES store_menu (menu_id),
    CONSTRAINT child_order_receive_type_check CHECK (receive_type IN ('TAKEOUT', 'DINE_IN')),
    CONSTRAINT child_order_status_check CHECK (status IN ('RECEIVED', 'COOKING', 'DONE', 'CANCELED'))
);

-- 아동 한 명에게 진행 중(접수 대기·조리 중) 주문은 하나뿐이다. 서비스가 "있나 보고 넣기"만 하면 주문 버튼 연타·두 기기에서
-- 둘이 생긴다 — 그래서 DB 가 막는다. 서비스는 이 이름으로 위반을 알아보고 409 active-order-exists 로 바꾼다.
CREATE UNIQUE INDEX uk_child_order_active ON child_order (child_id) WHERE status IN ('RECEIVED', 'COOKING');

-- 점주 목록은 "이 가게의 오늘 주문 + 날짜와 상관없이 끝나지 않은 주문"이다. 앞쪽은 아래 첫 인덱스가, 뒤쪽은 끝나지 않은 주문만 담는
-- 두 번째 인덱스가 받는다(OR 조건이라 한 인덱스로는 범위 조회가 안 된다). 첫 인덱스는 가게를 지울 때의 존재 확인도 받는다
CREATE INDEX idx_child_order_store_created ON child_order (store_id, created_at);
CREATE INDEX idx_child_order_store_active ON child_order (store_id) WHERE status IN ('RECEIVED', 'COOKING');
