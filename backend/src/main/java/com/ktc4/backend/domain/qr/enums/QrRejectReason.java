package com.ktc4.backend.domain.qr.enums;

/**
 * QR 문자열을 아동으로 해석하지 못한 이유. 서버 로그에만 쓰고 응답에는 싣지 않는다.
 *
 * <p>응답은 이유와 관계없이 {@code invalid-qr-token} 하나다. 이유를 응답에 담으면 값을 바꿔 넣어 보며
 * "한때 발급됐던 QR 인지" 같은 정보를 알아낼 수 있기 때문이다(로그인에서 없는 이메일과 틀린 비밀번호를
 * 구분하지 않는 것과 같은 이유).
 *
 * <p>"발급한 적 없음"과 "재발급으로 바뀐 옛 QR"은 지금 구분하지 않는다. 재발급할 때 옛 해시를 덮어쓰고
 * 이력을 남기지 않기 때문이다. 이력을 남기게 되면 그때 이유를 나눈다.
 */
public enum QrRejectReason {

    /** {@code v1.} 접두사와 43글자 base64url 형식이 아니다. DB 를 보기 전에 걸러진다. */
    FORMAT,

    /** 형식은 맞지만 그 토큰의 해시가 없다. 발급한 적 없거나, 재발급으로 바뀐 옛 QR 이다. */
    NOT_FOUND
}
